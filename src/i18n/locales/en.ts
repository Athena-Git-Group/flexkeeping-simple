/**
 * Recursively widens literal string types to `string` so that zh-TW / ja can
 * satisfy the en shape even though the workday fragments are `as const`.
 */
type Widen<T> = {
  [K in keyof T]: T[K] extends string ? string : Widen<T[K]>;
};

